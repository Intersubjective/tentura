// Run from packages/client: dart tool/generate_beacon_hierarchy_copy.dart
// Append --check to verify the checked-in Dart copy against the ARB catalogs.

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.isNotEmpty && (args.length != 1 || args.single != '--check')) {
    stderr.writeln(
      'Usage: dart tool/generate_beacon_hierarchy_copy.dart [--check]',
    );
    exitCode = 64;
    return;
  }

  final client = Platform.script.resolve('../');
  final output = File.fromUri(
    client.resolve('lib/features/beacon/domain/beacon_hierarchy_copy.dart'),
  );
  final source = StringBuffer()
    ..writeln('// Generated by tool/generate_beacon_hierarchy_copy.dart.')
    ..writeln()
    ..writeln('const beaconChildCommandConflictCopy = (');
  for (final locale in ['en', 'ru']) {
    final arb = File.fromUri(client.resolve('l10n/app_$locale.arb'));
    final messages = jsonDecode(arb.readAsStringSync());
    final copy = messages is Map<String, dynamic>
        ? messages['beaconChildCommandConflict']
        : null;
    if (copy is! String || copy.trim().isEmpty) {
      throw FormatException(
        'Missing beaconChildCommandConflict in ${arb.path}',
      );
    }
    final encoded = jsonEncode(copy).replaceAll(r'$', r'\$');
    final literal = copy.contains("'")
        ? encoded
        : "'${encoded.substring(1, encoded.length - 1)}'";
    source.writeln('  $locale: $literal,');
  }
  source.writeln(');');

  if (args.isEmpty) {
    output.writeAsStringSync(source.toString());
  } else if (!output.existsSync() ||
      output.readAsStringSync() != source.toString()) {
    stderr.writeln('Regenerate ${output.path} from the ARB catalogs.');
    exitCode = 1;
  }
}
